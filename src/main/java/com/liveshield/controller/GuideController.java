    @GetMapping("/guides")
    public String guides(
            @RequestParam(defaultValue = "en") String lang,
            Model model) {

        List<Map<String, String>> categories = List.of(
                Map.of(
                        "name", "Entry Control",
                        "description",
                        "Procedures for controlling people, vehicles and equipment entering the farm.",
                        "slug", "entry-control"),
                Map.of(
                        "name", "Equipment Hygiene",
                        "description",
                        "Cleaning and disinfection practices for shared farm equipment.",
                        "slug", "equipment-hygiene"),
                Map.of(
                        "name", "Waste Management",
                        "description",
                        "Safe collection, handling and disposal of farm waste.",
                        "slug", "waste-management"));

        model.addAttribute("categories", categories);
        model.addAttribute("selectedLanguage", lang);

        return "guides";
    }

    @GetMapping("/guides/{category}")
    public String guideDetails(
            @PathVariable String category,
            @RequestParam(defaultValue = "en") String lang,
            Model model) {

        Map<String, GuideContent> categoryGuides = guides.get(category);

        if (categoryGuides == null) {
            return "error";
        }

        GuideContent guide = categoryGuides.get(lang);

        if (guide == null) {
            guide = categoryGuides.get("en");
            lang = "en";
        }

        model.addAttribute("guide", guide);
        model.addAttribute("selectedLanguage", lang);

        return "guide-details";
    }

